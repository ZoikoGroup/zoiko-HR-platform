"""Endpoint inventory for the tenant-privacy control standard (ZHR-PRIV-001, Phase 0).

Walks the FastAPI route table and records, for every endpoint: path, methods, handler, the authentication/authorization
dependency chain, whether a platform user (role super_admin) can call it, and the privacy class of the route
(see app/core/privacy/routes.py). Writes docs/privacy/endpoint_inventory.md and endpoint_inventory.json.

    cd backend && python scripts/privacy_endpoint_inventory.py            # write the docs
    cd backend && python scripts/privacy_endpoint_inventory.py --check    # fail if the committed docs are stale

The route walker is also imported by the privacy tests, so the IDOR / platform-denial suites cover every route that
exists, including routes added later.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("ENVIRONMENT", "testing")
os.environ.setdefault("HR_DATABASE_URL", "sqlite:///:memory:")

DOCS = ROOT.parent / "docs" / "privacy"

# dependency name -> roles that can pass it (None = any signed-in user, [] = public)
ROLE_GUARDS = {
    "get_current_super_admin": ["super_admin"],
    "get_current_billing_owner": ["super_admin"],
    "get_current_admin": ["super_admin", "admin", "hr_admin"],
    "get_current_org_admin": ["super_admin", "admin"],
    "get_current_billing_admin": ["super_admin", "billing_admin"],
    "get_current_billing_actor": ["super_admin", "admin", "billing_admin"],
}
ORG_SCOPE_GUARDS = {"get_organization_id", "get_scoped_organization_id", "get_super_admin_organization_id", "require_organization_access"}


def _chain(dependant, seen=None):
    out = []
    for sub in dependant.dependencies:
        name = getattr(sub.call, "__name__", str(sub.call))
        out.append(name)
        out.extend(_chain(sub))
    return out


def iter_routes(app):
    """Yield every APIRoute with its full path (FastAPI >= 0.13x wraps included routers)."""
    from fastapi.routing import APIRoute

    def walk(routes, prefix=""):
        for r in routes:
            if isinstance(r, APIRoute):
                yield r
            elif hasattr(r, "original_router"):
                yield from walk(r.original_router.routes)
            elif hasattr(r, "routes"):
                yield from walk(r.routes)

    yield from walk(app.routes)


def inventory(app=None):
    if app is None:
        from app.main import app  # noqa: PLC0415
    from app.core.privacy.routes import classify_route

    rows = []
    for r in iter_routes(app):
        deps = _chain(r.dependant)
        guards = [d for d in deps if d in ROLE_GUARDS]
        authed = "get_current_user" in deps or bool(guards)
        if guards:
            roles = sorted(set.intersection(*[set(ROLE_GUARDS[g]) for g in guards]))
        elif authed:
            roles = ["any signed-in user"]
        else:
            roles = ["public"]
        rows.append({
            "path": r.path,
            "methods": sorted(m for m in r.methods if m not in ("HEAD", "OPTIONS")),
            "handler": f"{r.endpoint.__module__}.{r.endpoint.__name__}",
            "module": r.endpoint.__module__,
            "authenticated": authed,
            "role_guards": guards,
            "roles": roles,
            "org_scoped_dependency": sorted(set(deps) & ORG_SCOPE_GUARDS),
            "privacy_class": classify_route(r.path),
        })
    rows.sort(key=lambda x: (x["path"], x["methods"]))
    return rows


def render_markdown(rows) -> str:
    total = len(rows)
    by_class = {}
    for r in rows:
        by_class.setdefault(r["privacy_class"], []).append(r)
    plat = [r for r in rows if r["privacy_class"] == "DATA_PLANE" and ("super_admin" in r["roles"] or "any signed-in user" in r["roles"])]
    lines = [
        "# Endpoint inventory (generated)",
        "",
        "Generated by `backend/scripts/privacy_endpoint_inventory.py`. Do not edit by hand.",
        "",
        f"- Endpoints: **{total}**",
        *(f"- {k}: **{len(v)}**" for k, v in sorted(by_class.items())),
        f"- DATA_PLANE endpoints a platform (super_admin) token can *reach the dependency chain of*: **{len(plat)}** "
        "(all of them are refused for platform users by the platform gate in `get_current_user`, see `docs/privacy/trust_boundary.md`)",
        "",
        "Privacy classes: `PUBLIC` (no sign-in), `AUTH` (sign-in / session), `CONTROL_PLANE` (tenant lifecycle, plans, "
        "subscription billing, platform configuration and health), `DATA_PLANE` (tenant people, finance, customer or file data).",
        "",
        "| Path | Methods | Class | Roles that pass the guards | Org-scope dependency | Handler |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| `{r['path']}` | {', '.join(r['methods'])} | {r['privacy_class']} | {', '.join(r['roles'])} | "
                     f"{', '.join(r['org_scoped_dependency']) or '-'} | `{r['handler']}` |")
    lines += ["", "Next.js API routes / GraphQL: none. The frontend is a Vite + React single-page app and the backend exposes REST only.", ""]
    return "\n".join(lines)


def main(argv):
    rows = inventory()
    md = render_markdown(rows)
    DOCS.mkdir(parents=True, exist_ok=True)
    md_path, json_path = DOCS / "endpoint_inventory.md", DOCS / "endpoint_inventory.json"
    js = json.dumps(rows, indent=1, sort_keys=True)
    if "--check" in argv:
        stale = (not md_path.exists()) or md_path.read_text(encoding="utf-8") != md or json_path.read_text(encoding="utf-8") != js
        print("endpoint inventory is STALE: run scripts/privacy_endpoint_inventory.py" if stale else "endpoint inventory is up to date")
        return 1 if stale else 0
    md_path.write_text(md, encoding="utf-8")
    json_path.write_text(js, encoding="utf-8")
    print(f"wrote {len(rows)} endpoints to {md_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
