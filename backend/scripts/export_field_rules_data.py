"""Writes frontend/src/utils/fieldRulesData.js from the backend tables the field rules use (QA 2026-11, B7-B38).

The browser's rules (fieldRules.js) and the server's (app/core/field_rules.py) must accept the same countries, regions,
industries, postal formats and statutory labels. Those tables live here, so the browser's copy is generated:

    python scripts/export_field_rules_data.py            # rewrite the file
    python scripts/export_field_rules_data.py --check    # exit 1 if the file is out of date (run by the test suite)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core import business_ids, field_rules, regions  # noqa: E402
from app.modules.employee import import_countries  # noqa: E402

TARGET = Path(__file__).resolve().parents[2] / "frontend" / "src" / "utils" / "fieldRulesData.js"


def build() -> str:
    countries = sorted(([c, n] for c, n, _cur in regions.COUNTRIES), key=lambda x: x[1])
    aliases = {k: v for k, v in sorted(regions._ALIASES.items()) if k not in regions._CITY_ALIASES}
    statutory = {}
    for row in import_countries.COUNTRIES:
        iso = regions.country_code_strict(row["name"])
        if iso:
            statutory[iso] = {f: [label.replace(" (optional)", ""), example] for f, (_h, label, example) in row["ids"].items()}
    data = {
        "COUNTRIES": countries,
        "COUNTRY_ALIASES": aliases,
        "REGIONS": business_ids.REGIONS,
        "STATE_CODES": field_rules.STATE_CODES,
        "BUSINESS_IDS": {cc: f["ids"] for cc, f in sorted(business_ids.FORMATS.items())},
        "DEFAULT_BUSINESS_IDS": business_ids.DEFAULT["ids"],
        "EU_VAT": sorted(business_ids.EU_VAT),
        "INDUSTRIES": list(field_rules.INDUSTRIES),
        "POSTAL": {k: list(v) for k, v in sorted(field_rules.POSTAL.items())},
        "IBAN_COUNTRIES": sorted(field_rules.IBAN_COUNTRIES),
        "IBAN_LENGTHS": dict(sorted(field_rules._IBAN_LENGTHS.items())),
        "STATUTORY": statutory,
        "GENERIC_STATUTORY": {f: [label, example] for f, (_h, label, example) in import_countries.GENERIC["ids"].items()},
    }
    body = "\n".join(f"export const {k} = {json.dumps(v, ensure_ascii=False)};" for k, v in data.items())
    return ("// GENERATED by backend/scripts/export_field_rules_data.py from the server's tables. Do not edit by hand:\n"
            "// change the backend table and re-run the script (a backend test fails when this file is out of date).\n"
            f"{body}\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
